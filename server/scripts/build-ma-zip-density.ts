// Builds src/rules/ma-zip-density.ts: population density for every Massachusetts
// ZIP Code Tabulation Area, from the 2020 Census via TIGERweb (no API key needed).
//
// Run from server/: npm run build:zip-density

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const LAYER =
  'https://tigerweb.geo.census.gov/arcgis/rest/services/TIGERweb/tigerWMS_Census2020/MapServer/84/query';
const SQ_METERS_PER_SQ_MILE = 2_589_988.11;
const PAGE_SIZE = 500;

interface Feature {
  attributes: { ZCTA5: string; POP100: number; AREALAND: number };
}

async function fetchPage(offset: number): Promise<Feature[]> {
  const params = new URLSearchParams({
    // MA ZIP codes run 01000-02799
    where: "ZCTA5 >= '01000' AND ZCTA5 < '02800'",
    outFields: 'ZCTA5,POP100,AREALAND',
    returnGeometry: 'false',
    orderByFields: 'ZCTA5',
    resultOffset: String(offset),
    resultRecordCount: String(PAGE_SIZE),
    f: 'json',
  });
  const res = await fetch(`${LAYER}?${params}`);
  if (!res.ok) throw new Error(`TIGERweb returned HTTP ${res.status}`);
  const body = (await res.json()) as { features?: Feature[]; error?: { message: string } };
  if (body.error) throw new Error(`TIGERweb error: ${body.error.message}`);
  return body.features ?? [];
}

async function main() {
  const density: Record<string, number> = {};
  for (let offset = 0; ; offset += PAGE_SIZE) {
    const page = await fetchPage(offset);
    for (const { attributes: a } of page) {
      if (a.AREALAND > 0) {
        density[a.ZCTA5] = Math.round(a.POP100 / (a.AREALAND / SQ_METERS_PER_SQ_MILE));
      }
    }
    if (page.length < PAGE_SIZE) break;
  }

  const count = Object.keys(density).length;
  if (count < 400) throw new Error(`Only ${count} ZIP codes returned; expected ~500. Not writing.`);

  const out = `// GENERATED by scripts/build-ma-zip-density.ts - do not edit by hand.
// People per square mile for each Massachusetts ZCTA, 2020 Census (TIGERweb).
// ${count} ZIP codes.

export const maZipDensity: Readonly<Record<string, number>> = ${JSON.stringify(density, null, 2)};
`;
  const target = fileURLToPath(new URL('../src/rules/ma-zip-density.ts', import.meta.url));
  await writeFile(target, out);
  console.log(`Wrote ${count} ZIP codes to ${target}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
